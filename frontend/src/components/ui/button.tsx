/**
 * A11y: `data-disabled:opacity-50` in the base classes is for call sites
 * that pass Base UI's `focusableWhenDisabled`. That prop swaps the native
 * `disabled` attribute for `aria-disabled`, so `disabled:opacity-50` no
 * longer matches -- used on submit buttons that disable themselves mid-
 * request, where a natively disabled button would drop keyboard focus to
 * <body> the moment it was activated (WCAG 2.4.3).
 */
function Button({
  className,
  variant = "default",
  size = "default",
  ...props
}: ButtonPrimitive.Props & VariantProps<typeof buttonVariants>) {
  return (
    <ButtonPrimitive
      data-slot="button"
      className={cn(buttonVariants({ variant, size, className }))}
      {...props}
    />
  )
}

export { Button, buttonVariants }
